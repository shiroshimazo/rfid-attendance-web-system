-- Keep the public role row synchronized with Supabase Auth accounts.
create or replace function public.handle_auth_user_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  requested_role public.user_role;
begin
  requested_role := case
    when new.raw_app_meta_data ->> 'role' in ('admin', 'teacher', 'student')
      then (new.raw_app_meta_data ->> 'role')::public.user_role
    else 'student'::public.user_role
  end;

  insert into public.users (id, email, role)
  values (new.id, coalesce(new.email, ''), requested_role)
  on conflict (id) do update
    set email = excluded.email,
        role = excluded.role;

  return new;
end;
$$;

create trigger on_auth_user_change
after insert or update of email, raw_app_meta_data on auth.users
for each row execute function public.handle_auth_user_change();

insert into public.users (id, email, role)
select
  id,
  coalesce(email, ''),
  case
    when raw_app_meta_data ->> 'role' in ('admin', 'teacher', 'student')
      then (raw_app_meta_data ->> 'role')::public.user_role
    else 'student'::public.user_role
  end
from auth.users
where email is not null
on conflict (id) do nothing;

-- Security-definer helpers avoid recursive users-table RLS checks.
create or replace function public.current_user_role()
returns public.user_role
language sql
stable
security definer
set search_path = public
as $$
  select role from public.users where id = auth.uid()
$$;

create or replace function public.current_student_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id from public.students where user_id = auth.uid()
$$;

revoke all on function public.current_user_role() from public;
revoke all on function public.current_student_id() from public;
grant execute on function public.current_user_role() to authenticated;
grant execute on function public.current_student_id() to authenticated;

